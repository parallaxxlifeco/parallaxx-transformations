        const onScroll = () => {
          if(ticking) return; ticking = true;
          requestAnimationFrame(() => {
            nav.classList.toggle('is-stuck', window.scrollY > 40);
            ticking = false;
          });
        };
        window.addEventListener('scroll', onScroll, {passive:true});
